/*
 * What a human typed in a WorkBuddy / CodeBuddy Code user message, and which user messages are not human input
 * (docs/formats/buddy-family.md sections 4.1 and 4.2; spec 4.3). The flags are read from `providerData`, where the
 * engine writes them, never from the top level of the record (format reference D1).
 */

type Obj = Record<string, unknown>;
const isObject = (v: unknown): v is Obj => typeof v === 'object' && v !== null && !Array.isArray(v);

const SYSTEM_REMINDER = /<system-reminder\b[^>]*>[\s\S]*?<\/system-reminder>\s*/g;
const USER_QUERY = /<user_query>([\s\S]*?)<\/user_query>/g;
const COMMAND_CAVEAT =
  '<system-reminder data-role="command-caveat">Caveat: The messages below were generated by the user while running local commands. DO NOT respond to these messages or otherwise consider them in your response unless the user explicitly asks you to.</system-reminder>';
const CLEAR_COMMAND = /<command_name>\s*\/clear\s*<\/command_name>/;
/**
 * Tags of a local-command echo (bash / memory input, a slash command) or output (local command, bash stdout / stderr):
 * the engine shows such a part as a command, not as a prompt (its parseInput / parseOutput). The engine tests the bare
 * names; here the opening tag is required so that a human mentioning a name is not taken for one.
 */
const LOCAL_COMMAND_TAGS = [
  '<bash-input',
  '<user-memory-input',
  '<user-memory-scope',
  '<command-name',
  '<command_name',
  '<command-message',
  '<command-args',
  '<local-command-stdout',
  '<bash-stdout',
  '<bash-stderr',
];
/** Envelopes of injected (non-human) text (format reference 4.1, "Other envelopes"). */
const INJECTED_ENVELOPES = [/<cb_summary\b/i, /<conversation_history_summary\b/i, /<task-notification\b/i, /<monitor-event\b/i, /<teammate-message\b/i, /<turn_aborted\b/i];
const IMAGE_PATH = /<image_local_path>[\s\S]*?<\/image_local_path>/g;
const CHANNEL = /^\s*<channel\b[^>]*>([\s\S]*?)<\/channel>\s*$/;

/** The text parts of a user message's content: a string is one part; `input_text` parts of an array; others none. */
function textParts(content: unknown): string[] | null {
  if (typeof content === 'string') return [content];
  if (!Array.isArray(content)) return null;
  const out: string[] = [];
  for (const p of content) {
    if (typeof p === 'string') out.push(p);
    else if (isObject(p) && p.type === 'input_text' && typeof p.text === 'string') out.push(p.text);
  }
  return out;
}

/** The engine's isSystemInternalMessage: a reminder without a query, the command caveat, a /clear command. */
function isSystemInternal(part: string): boolean {
  const t = part.trimStart();
  return (t.startsWith('<system-reminder') && !t.includes('<user_query>')) || part === COMMAND_CAVEAT || CLEAR_COMMAND.test(part);
}

const isLocalCommand = (part: string): boolean => LOCAL_COMMAND_TAGS.some((tag) => part.includes(tag));
const isInjected = (part: string): boolean => INJECTED_ENVELOPES.some((re) => re.test(part));

/**
 * What the human typed in a user message's content, or null when nothing remains (format reference 4.1). Per text
 * part: system-internal parts (a reminder without a query, the command caveat, /clear), local-command echoes and
 * outputs, and injected envelopes are dropped; reminders are stripped. When any part has a `<user_query>`, the result
 * is the bodies of every `<user_query>` (in order, joined by a line break) and nothing else; otherwise the remaining
 * parts joined by a line break (`<image_local_path>` markup removed, a `<channel>` envelope replaced by its content).
 */
export function humanText(content: unknown): string | null {
  const parts = textParts(content);
  if (parts === null) return null;
  const queries: string[] = [];
  const others: string[] = [];
  let sawQuery = false;
  for (const part of parts) {
    if (isSystemInternal(part)) continue;
    if (part.includes('<user_query>')) {
      sawQuery = true;
      for (const m of part.matchAll(USER_QUERY)) {
        const body = m[1]!.trim();
        if (body !== '') queries.push(body);
      }
      continue;
    }
    if (sawQuery) continue;
    let s = part.replace(SYSTEM_REMINDER, '').trim();
    if (s === '' || isLocalCommand(s) || isInjected(s)) continue;
    const channel = CHANNEL.exec(s);
    if (channel !== null) s = channel[1]!;
    s = s.replace(IMAGE_PATH, '').trim();
    if (s !== '') others.push(s);
  }
  const text = (sawQuery ? queries : others).join('\n').trim();
  return text === '' ? null : text;
}

/** The text of a user message (its `input_text` parts joined), for the content tests of the engine predicates. */
function messageText(content: unknown): string {
  return (textParts(content) ?? []).join('');
}

/** The engine's compaction-boundary predicate (isStructuredCompactBoundaryMessage / hasCompactBoundaryContent). */
function isCompactBoundary(pd: Obj, content: unknown): boolean {
  if (pd.isCompacted === true || pd.isSummary === true) return true;
  if (pd.isCompactInternal === true || isCompactAgent(pd.agent)) return false;
  if (typeof pd.compactType === 'string') return true;
  const text = messageText(content);
  return /<cb_summary\b/i.test(text) || /<conversation_history_summary\b/i.test(text) || /data-role=["']compact-summary["']/i.test(text);
}

/** `agent` names the compaction agent (compared case-insensitively, format reference D2). */
export function isCompactAgent(agent: unknown): boolean {
  return typeof agent === 'string' && agent.toLowerCase() === 'compact';
}

/**
 * What a user-role message is (format reference 4.2), from its `providerData` flags:
 * - 'compaction': the compaction boundary carrying the summary (isCompacted / isSummary / compactType / summary content);
 * - 'hidden': skipRun, isCompactInternal, the compact agent's messages, teammate notifications, isAdditionalData, isMeta
 *   (error-recovery and continuation reminders, notification injections, cron triggers), and anything that is not a
 *   user-role message;
 * - 'queued-prompt': a real prompt injected mid-turn (`startsNewUserRequest === false` without isMeta);
 * - 'prompt': the rest (queueHold included).
 */
export function classifyUserMessage(rec: unknown): 'prompt' | 'queued-prompt' | 'compaction' | 'hidden' {
  if (!isObject(rec) || rec.type !== 'message' || rec.role !== 'user') return 'hidden';
  const pd = isObject(rec.providerData) ? rec.providerData : {};
  if (isCompactBoundary(pd, rec.content)) return 'compaction';
  if (Boolean(pd.skipRun) || pd.isCompactInternal === true || isCompactAgent(pd.agent)) return 'hidden';
  const teammate = isObject(pd.teammateMessage) && typeof pd.teammateMessage.from === 'string';
  if (teammate || /<teammate-message\b/i.test(messageText(rec.content))) return 'hidden';
  if (pd.isAdditionalData === true || pd.isMeta === true) return 'hidden';
  if (pd.startsNewUserRequest === false) return 'queued-prompt';
  return 'prompt';
}
